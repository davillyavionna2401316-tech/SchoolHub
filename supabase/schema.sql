-- SchoolHub: persistent aspiration/ticket storage
-- Run this script in Supabase SQL Editor.
-- This creates a new table so the existing public.aspirasi table is not overwritten.

create table if not exists public.aspirasi_laporan (
  id bigint generated by default as identity primary key,
  nomor_tiket text not null unique,
  nama_pelapor text not null default 'Anonim',
  kategori_pelapor text not null default 'Siswa',
  kategori_laporan text not null,
  judul text not null,
  deskripsi text not null,
  lampiran_url text,
  email_kontak text,
  kode_akses_publik text not null,
  petugas_pj text not null default 'Belum Ditentukan',
  prioritas text not null default 'Sedang',
  status text not null default 'Diterima',
  tanggal_target_selesai date,
  tanggal_penyelesaian date,
  ringkasan_hasil text,
  tindakan_akhir text,
  catatan_penyelesaian text,
  alasan_penolakan text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.aspirasi_riwayat (
  id bigint generated by default as identity primary key,
  aspirasi_id bigint not null references public.aspirasi_laporan(id) on delete cascade,
  tanggal timestamptz not null default now(),
  petugas text not null default 'Sistem',
  jenis_tindakan text not null,
  uraian text not null,
  hasil_sementara text,
  kendala text,
  rencana_berikutnya text,
  status_pada_saat_ini text,
  tampilkan_ke_publik boolean not null default false
);

alter table public.aspirasi_laporan enable row level security;
alter table public.aspirasi_riwayat enable row level security;

-- Public visitors may submit a report, but cannot read reports directly.
drop policy if exists "Public can submit aspiration reports" on public.aspirasi_laporan;
create policy "Public can submit aspiration reports"
on public.aspirasi_laporan for insert to anon
with check (true);

-- Only authenticated Supabase users (admin accounts created by the project owner)
-- may view and manage reports.
drop policy if exists "Authenticated staff can read aspiration reports" on public.aspirasi_laporan;
create policy "Authenticated staff can read aspiration reports"
on public.aspirasi_laporan for select to authenticated
using (true);

drop policy if exists "Authenticated staff can update aspiration reports" on public.aspirasi_laporan;
create policy "Authenticated staff can update aspiration reports"
on public.aspirasi_laporan for update to authenticated
using (true) with check (true);

drop policy if exists "Public can submit aspiration history" on public.aspirasi_riwayat;
create policy "Public can submit aspiration history"
on public.aspirasi_riwayat for insert to anon
with check (true);

drop policy if exists "Authenticated staff can read aspiration history" on public.aspirasi_riwayat;
create policy "Authenticated staff can read aspiration history"
on public.aspirasi_riwayat for select to authenticated
using (true);

drop policy if exists "Authenticated staff can manage aspiration history" on public.aspirasi_riwayat;
create policy "Authenticated staff can manage aspiration history"
on public.aspirasi_riwayat for all to authenticated
using (true) with check (true);

grant usage on schema public to anon, authenticated;
grant insert on public.aspirasi_laporan to anon;
grant select, update on public.aspirasi_laporan to authenticated;
grant insert on public.aspirasi_riwayat to anon;
grant select, insert, update, delete on public.aspirasi_riwayat to authenticated;
